		const LANGUAGE = { id: "es", label: "Español", fallback: "en" };
		const MENU_LABELS = {"application":"Aplicación","edit":"Edición","menuBar":"Menú de la aplicación"};
		/**
		* Traduce el menú de ventana que DSH dibuja en Windows (preload), cuyos
		* rótulos solo contemplan en/zh. Reaplica si el preload los vuelve a poner
		* en inglés al cambiar el idioma del documento.
		*/
		function patchWindowMenu() {
			const lang = document.documentElement.lang || "";
			if (!lang.toLowerCase().startsWith("es")) return;
			for (const host of document.querySelectorAll("[data-windows-menu]")) {
				const root = host.shadowRoot;
				if (root === null) continue;
				const buttons = root.querySelectorAll("button");
				if (buttons.length >= 2) {
					if (buttons[0].textContent !== MENU_LABELS.application) buttons[0].textContent = MENU_LABELS.application;
					if (buttons[1].textContent !== MENU_LABELS.edit) buttons[1].textContent = MENU_LABELS.edit;
				}
				const bar = root.querySelector('[role="menubar"]');
				if (bar !== null && bar.getAttribute("aria-label") !== MENU_LABELS.menuBar) bar.setAttribute("aria-label", MENU_LABELS.menuBar);
			}
		}
		var menuObserver = null;
		function installWindowMenuPatch() {
			if (typeof document === "undefined") return;
			patchWindowMenu();
			if (menuObserver !== null) return;
			menuObserver = new MutationObserver(() => patchWindowMenu());
			menuObserver.observe(document.documentElement, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ["lang"] });
		}
		function apply(ctx) {
			ctx.effect(() => ctx.locale.addLanguage(LANGUAGE), "locale-es: language");
			for (const [ns, dict] of Object.entries(es)) {
				ctx.effect(() => ctx.locale.register(ns, "es", dict), "locale-es: " + ns);
			}
			installWindowMenuPatch();
			ctx.effect(() => () => {
				if (menuObserver !== null) menuObserver.disconnect();
				menuObserver = null;
			}, "locale-es: window menu patch");
		}
		exports.apply = apply;
		exports.inject = ["locale"];
		return module.exports;
